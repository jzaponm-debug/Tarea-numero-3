    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        if (indice == 0) {
            JOptionPane.showMessageDialog(this, "Primero debes cargar los datos.");
            return;
        }

        double suma = 0;
        int diasCalidos = 0;
        int diasFrescos = 0;

        for (int i = 0; i < 6; i++) {
            suma = suma + temperaturas[i];

            if (temperaturas[i] >= 25.0) {
                diasCalidos++;
            } else {
                diasFrescos++;
            }
        }

        double promedio = suma / 6.0;

        taResultados.setText("Análisis Climático\n");
        taResultados.append("Promedio de Temperatura: " + String.format("%.2f", promedio) + "\n");
        taResultados.append("Días Cálidos (>=25°): " + diasCalidos + "\n");
        taResultados.append("Días Frescos (<25°): " + diasFrescos + "\n");
    }//GEN-LAST:event_btnCalcularActionPerformed

    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        indice = 0;
        try {
            File archivo = new File("temp/temperaturas.txt");
            Scanner lector = new Scanner(archivo);

            while (lector.hasNextLine() && indice < 6) {
                String linea = lector.nextLine();
                temperaturas[indice] = Double.parseDouble(linea);
                indice++;
            }
            lector.close();
            JOptionPane.showMessageDialog(this, "Datos cargados en memoria exitosamente.");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al leer. Verifica que el archivo temperaturas.txt exista dentro de la carpeta temp.");
        }
    }//GEN-LAST:event_btnCargarActionPerformed

