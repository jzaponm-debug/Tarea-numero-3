    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
        try {

            Artista nuevoArtista = new Artista();

            nuevoArtista.nombre = txtNombreArt.getText();
            nuevoArtista.paisOrigen = txtPais.getText();
            nuevoArtista.oyentesMensuales = Integer.parseInt(txtOyentes.getText());

            taResultados.append("Artista Creado: " + nuevoArtista.nombre
                    + " | País: " + nuevoArtista.paisOrigen
                    + " | Oyentes: " + nuevoArtista.oyentesMensuales + "\n");

            txtNombreArt.setText("");
            txtPais.setText("");
            txtOyentes.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Los oyentes deben ser un número entero.");
        }
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
        try {

            Cancion nuevaCancion = new Cancion();

            nuevaCancion.titulo = txtTitulo.getText();
            nuevaCancion.nombreArtista = txtInterprete.getText();
            nuevaCancion.duracionSegundos = Integer.parseInt(txtDuracion.getText());
            nuevaCancion.genero = txtGenero.getText();

            taResultados.append("Canción Creada: " + nuevaCancion.titulo
                    + " de " + nuevaCancion.nombreArtista
                    + " | Duración: " + nuevaCancion.duracionSegundos + "s"
                    + " | Género: " + nuevaCancion.genero + "\n");

            txtTitulo.setText("");
            txtInterprete.setText("");
            txtDuracion.setText("");
            txtGenero.setText("");

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: La duración debe ser un número entero.");
        }
    }//GEN-LAST:event_btnCrearCancionActionPerformed

