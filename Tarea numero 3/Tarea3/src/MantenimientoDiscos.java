    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String discoBuscado = txtBuscar.getText().trim();
        boolean encontrado = false;

        for (int i = 0; i < 5; i++) {

            if (titulos[i] != null && titulos[i].equalsIgnoreCase(discoBuscado)) {
                lblAnioActual.setText(String.valueOf(anios[i]));
                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            JOptionPane.showMessageDialog(this, "Álbum no encontrado en el catálogo.");
            lblAnioActual.setText("-");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String discoBuscado = txtBuscar.getText().trim();
        String nuevoAnioTexto = txtNuevoAnio.getText().trim();

        if (nuevoAnioTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa un año válido.");
            return;
        }

        try {
            int nuevoAnio = Integer.parseInt(nuevoAnioTexto);
            boolean actualizado = false;

            for (int i = 0; i < 5; i++) {
                if (titulos[i] != null && titulos[i].equalsIgnoreCase(discoBuscado)) {
                    anios[i] = nuevoAnio;
                    lblAnioActual.setText(String.valueOf(nuevoAnio));
                    actualizado = true;
                    break;
                }
            }

            if (actualizado) {

                FileWriter archivo = new FileWriter("temp/discos.csv.txt", false);
                for (int i = 0; i < 5; i++) {
                    if (titulos[i] != null) {
                        archivo.write(titulos[i] + "," + anios[i] + "\n");
                    }
                }
                archivo.close();
                JOptionPane.showMessageDialog(this, "Registro actualizado y guardado correctamente.");
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo actualizar. Busca el álbum primero.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar el archivo: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

