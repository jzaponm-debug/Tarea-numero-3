    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (contador < 5) {
            try {

                Videojuego nuevoJuego = new Videojuego();

                nuevoJuego.titulo = txtTituloJuego.getText();
                nuevoJuego.consola = txtConsola.getText();
                nuevoJuego.precio = Double.parseDouble(txtPrecio.getText());

                catalogo[contador] = nuevoJuego;
                contador++;

                javax.swing.JOptionPane.showMessageDialog(this, "Juego agregado al catálogo.");

                txtTituloJuego.setText("");
                txtConsola.setText("");
                txtPrecio.setText("");

            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Ingresa un número válido en la última caja.");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "El catálogo está lleno (Máximo 5 juegos).");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed

        taCatalogo.setText("--- CATÁLOGO DE VIDEOJUEGOS ---\n");

        if (contador == 0) {
            taCatalogo.append("El catálogo está vacío.\n");
            return;
        }

        for (int i = 0; i < contador; i++) {
            if (catalogo[i] != null) {
                taCatalogo.append("- " + catalogo[i].titulo
                        + " (" + catalogo[i].consola + ") | Valor: " + catalogo[i].precio + "\n");
            }
        }
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        String tituloEliminar = txtTituloJuego.getText().trim();
        boolean encontrado = false;

        for (int i = 0; i < contador; i++) {
            if (catalogo[i] != null && catalogo[i].titulo.equalsIgnoreCase(tituloEliminar)) {
                catalogo[i] = null; // Eliminamos el objeto
                encontrado = true;
                javax.swing.JOptionPane.showMessageDialog(this, "Juego eliminado. Presiona Mostrar Catálogo para actualizar.");
                txtTituloJuego.setText("");
                break;
            }
        }

        if (!encontrado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Para eliminar, escribe el título exacto en la primera caja.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

