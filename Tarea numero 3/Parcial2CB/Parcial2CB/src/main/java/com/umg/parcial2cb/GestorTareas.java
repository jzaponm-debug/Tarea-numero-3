    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

        if (indice < 5) {

            String nuevaTarea = txtTarea.getText();

            tareas[indice] = nuevaTarea;

            taListado.append((indice + 1) + ". " + nuevaTarea + "\n");

            indice = indice + 1;

            txtTarea.setText("");

        } else {
            JOptionPane.showMessageDialog(this, "Ya ingresaste las 5 tareas permitidas.");
        }

        //Limpia el texto de notas luego de agregado al arreglo
        txtTarea.setText("");
        //Crear una ventana de mensaje
        JOptionPane.showMessageDialog(this, "Tarea creada con Exito");


    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO: Ingresar aquí la lógica para generar el archivo

        //No cambiar la ubicacion, esto creará el archivo dentro de la carpeta temp que esta en el proyecto
        String ubicacion = "temp/";
        try {

            java.io.FileWriter archivo = new java.io.FileWriter(ubicacion + "GabrielZapon_agenda.txt");

            archivo.write("Agenda de Tareas\n");

            for (int i = 0; i < 5; i++) {
                if (tareas[i] != null) {
                    archivo.write((i + 1) + ". " + tareas[i] + "\n");
                }
            }

            archivo.close();
            JOptionPane.showMessageDialog(this, "Agenda exportada con éxito en la carpeta temp.");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al exportar la agenda: " + e.getMessage());
        }


    }//GEN-LAST:event_btnExportarActionPerformed

