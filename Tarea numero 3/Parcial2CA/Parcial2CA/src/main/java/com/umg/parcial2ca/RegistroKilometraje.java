    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO: Ingresar aquí la lógica para agregar
        if (indice < 7) {

            double valor = Double.parseDouble(txtKilometraje.getText());

            kilometrajes[indice] = valor;

            indice = indice + 1;

            txtKilometraje.setText("");
            JOptionPane.showMessageDialog(this, "Ruta agregada exitosamente.");
        } else {
            // Si la caja ya está llena, avisamos
            JOptionPane.showMessageDialog(this, "Ya llenaste los 7 días de la semana.");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        // TODO: Ingresar aquí la lógica para generar el reporte
        String ubicacion = "temp/";
        double total = 0;
        double promedio = 0;

        for (int i = 0; i < 7; i++) {
            total = total + kilometrajes[i];
        }

        promedio = total / 7;

        try {
            // Recuerda cambiar "sunombre" por tu nombre real
            java.io.FileWriter archivo = new java.io.FileWriter(ubicacion + "GabrielZapon_reporte_rutas.txt");
            archivo.write("Reporte Semanal de Rutas\n");
            archivo.write("Total de Kilómetros: " + total + "\n");
            archivo.write("Promedio Diario: " + promedio + "\n");
            archivo.close();

            JOptionPane.showMessageDialog(this, "Reporte generado con éxito en la carpeta temp.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al generar el reporte: " + e.getMessage());
        }
        //No cambiar esta ubicacion 
        //El archivo se debe crear dentro de la carpeta temp que esta en el proyecto

    }//GEN-LAST:event_btnGenerarReporteActionPerformed

